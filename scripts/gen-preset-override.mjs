#!/usr/bin/env node
/**
 * Generate `cordis.patch.yml` from the installed/shipped `cordis` preset.
 *
 * We must override `preset-cordis` by id (duplicate preset ids are rejected)
 * and a preset's `config.plugins` array is not a Loader group, so there is no
 * incremental patch target. This script copies the shipped plugin list and
 * appends exactly one row. Re-run it after a DSH upgrade.
 */
import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, resolve } from 'node:path'

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')

function argValue(name) {
  const index = process.argv.indexOf(name)
  return index >= 0 ? process.argv[index + 1] : undefined
}

export function defaultSourcePath() {
  return resolve(packageRoot, '..', '..', 'dsh-ref', 'source', '@deepseek-ai', 'dsh-web-app', 'presets', 'cordis.patch.yml')
}

function shiftLeft(text, amount) {
  return text.split(/\r?\n/u).map((line) => {
    let count = 0
    while (count < amount && line[count] === ' ') count += 1
    return count === amount ? line.slice(amount) : line
  })
}

export function buildPatch(sourceText, { sourceLabel = 'dsh-web-app/presets/cordis.patch.yml', dshVersion = '0.2.1-rc.2' } = {}) {
  const hash = createHash('sha256').update(sourceText).digest('hex')
  const lines = sourceText.replace(/\r\n/gu, '\n').split('\n')
  const pluginsAt = lines.findIndex((line) => /^ {8}plugins:\s*$/u.test(line))
  if (pluginsAt < 0) throw new Error('source preset has no 8-space "plugins:" line')
  const block = lines.slice(pluginsAt + 1)
  while (block.length > 0 && block.at(-1).trim() === '') block.pop()
  const shifted = shiftLeft(block.join('\n'), 4).join('\n')
  const toolRow = [
    '      - id: tool-dsh-auto-restart',
    '        name: dsh-auto-restart/tool',
  ].join('\n')
  return [
    '# Generated by scripts/gen-preset-override.mjs — do not edit by hand.',
    `# Source: ${sourceLabel} (dsh ${dshVersion})`,
    `# Source sha256: ${hash}`,
    '',
    '- insert:',
    '    - id: dsh-auto-restart',
    '      name: dsh-auto-restart',
    '- id: preset-cordis',
    "  name: '@deepseek-ai/dsh-agent-preset'",
    '  config:',
    '    id: cordis',
    '    order: 4',
    '    plugins:',
    shifted,
    toolRow,
    '',
  ].join('\n')
}

if (process.argv[1] !== undefined && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const sourcePath = resolve(argValue('--source') ?? defaultSourcePath())
  const outPath = resolve(argValue('--out') ?? resolve(packageRoot, 'cordis.patch.yml'))
  const sourceText = readFileSync(sourcePath, 'utf8')
  const output = buildPatch(sourceText, { sourceLabel: sourcePath })
  writeFileSync(outPath, output, 'utf8')
  console.log(`wrote ${outPath} from ${sourcePath}`)
}
